/// Draws a [GroupReport] as a one-page A4 PDF (Report Preview → Export
/// PDF), laid out like the on-screen preview (Figma 23).
///
/// Uses the `pdf` package (pure Dart, works offline). Its built-in
/// Helvetica font has no ₱ sign, so amounts are written "PHP 2,500.00".
library;

import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import 'package:bahinko/utils/currency.dart';
import 'package:bahinko/utils/group_report.dart';

const _green = PdfColor.fromInt(0xFF0A9B7A);
const _deep = PdfColor.fromInt(0xFF064E3B);
const _mint = PdfColor.fromInt(0xFFE8F7F0);
const _muted = PdfColor.fromInt(0xFF6B7C76);
const _orange = PdfColor.fromInt(0xFFB8610A);

String _php(int cents) => formatMoney(cents).replaceAll('₱', 'PHP ');

Future<Uint8List> buildReportPdf(GroupReport r) {
  final doc = pw.Document(title: '${r.groupName} expense report');

  pw.Widget headerCell(String text, {bool right = false}) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 6),
    child: pw.Text(
      text.toUpperCase(),
      textAlign: right ? pw.TextAlign.right : pw.TextAlign.left,
      style: pw.TextStyle(
        fontSize: 8,
        color: _deep,
        fontWeight: pw.FontWeight.bold,
      ),
    ),
  );
  pw.Widget cell(
    String text, {
    bool right = false,
    bool bold = false,
    PdfColor? color,
  }) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
    child: pw.Text(
      text,
      textAlign: right ? pw.TextAlign.right : pw.TextAlign.left,
      style: pw.TextStyle(
        fontSize: 10,
        color: color,
        fontWeight: bold ? pw.FontWeight.bold : null,
      ),
    ),
  );

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(40),
      footer: (context) => pw.Align(
        alignment: pw.Alignment.center,
        child: pw.Text(
          'Generated by BahinKo · ${longDate(r.generatedAt)} · '
          'Page ${context.pageNumber} of ${context.pagesCount}',
          style: const pw.TextStyle(fontSize: 8, color: _muted),
        ),
      ),
      build: (context) => [
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'BahinKo',
              style: pw.TextStyle(
                fontSize: 18,
                color: _deep,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.Text(
              'Expense Report',
              style: const pw.TextStyle(fontSize: 10, color: _muted),
            ),
          ],
        ),
        pw.Divider(color: _mint, thickness: 2),
        pw.SizedBox(height: 8),
        pw.Text(
          r.groupName,
          style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold),
        ),
        // Helvetica has no en dash, so use a plain hyphen in the PDF.
        pw.Text(
          r.subtitle.replaceAll('\u2013', '-'),
          style: const pw.TextStyle(color: _muted),
        ),
        pw.SizedBox(height: 14),
        pw.Table(
          columnWidths: const {
            0: pw.FlexColumnWidth(1.2),
            1: pw.FlexColumnWidth(3),
            2: pw.FlexColumnWidth(1.6),
            3: pw.FlexColumnWidth(1.8),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: _mint),
              children: [
                headerCell('Date'),
                headerCell('Expense'),
                headerCell('Paid by'),
                headerCell('Amount', right: true),
              ],
            ),
            for (final row in r.rows)
              pw.TableRow(
                children: [
                  cell(shortDate(row.date)),
                  cell(row.title),
                  cell(row.paidBy),
                  cell(_php(row.amountCents), right: true, bold: true),
                ],
              ),
          ],
        ),
        pw.Divider(color: _mint),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'TOTAL',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
            ),
            pw.Text(
              _php(r.totalCents),
              style: pw.TextStyle(
                fontSize: 16,
                color: _green,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ],
        ),
        pw.SizedBox(height: 18),
        pw.Text(
          'Per person',
          style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold),
        ),
        pw.SizedBox(height: 6),
        pw.Table(
          columnWidths: const {
            0: pw.FlexColumnWidth(2),
            1: pw.FlexColumnWidth(2),
            2: pw.FlexColumnWidth(3),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: _mint),
              children: [
                headerCell('Name'),
                headerCell('Share'),
                headerCell('Status', right: true),
              ],
            ),
            for (final p in r.people)
              pw.TableRow(
                children: [
                  cell(p.name),
                  cell(_php(p.shareCents)),
                  cell(
                    p.status.replaceAll('₱', 'PHP '),
                    right: true,
                    bold: true,
                    color: p.kind == StatusKind.good ? _green : _orange,
                  ),
                ],
              ),
          ],
        ),
        pw.SizedBox(height: 18),
        pw.Text(
          'Shares follow how each expense was split (equal, by item, exact, '
          'percent or shares).',
          style: const pw.TextStyle(fontSize: 9, color: _muted),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          'Payments are made in GCash, Maya or cash. BahinKo never holds money.',
          style: const pw.TextStyle(fontSize: 9, color: _muted),
        ),
      ],
    ),
  );
  return doc.save();
}
